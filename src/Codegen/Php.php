<?php

declare(strict_types=1);

namespace JOetjen\Dextrin\Codegen;

use JOetjen\Dextrin\Schema\Compiled;
use JOetjen\Dextrin\Schema\Tree;

/**
 * PHP code from DXNS (T685, design/codegen-php.md), the port of dextrin's
 * `Dextrin.Codegen.Elixir`. For each `%schema` of a tree of `.dxns` files
 * ({@see Tree}) it writes two files, PSR-4 under the output directory:
 *
 * - `Order.php`, **the user's**: `class Order extends AbstractOrder`,
 *   written once and never rewritten. Hand-written upgrades and anything
 *   else of the user's own go here.
 * - `AbstractOrder.php`, **the generator's**: rewritten on every run. Its
 *   readonly properties are the latest version's fields; it holds a
 *   reader and a checker per version (`readV1()`, `conformV1()`), an
 *   upgrade step between each version and the next, `read()`, which
 *   dispatches on the version a struct was written with, `validate()` and
 *   `toDxn()`. Every check is code of its own: no schema is read when it
 *   runs ({@see Runtime}).
 *
 * And one `Decoder.php`: `Decoder::decode()` decodes DXN text and reads
 * every struct of a known schema into its class.
 *
 * What is written by hand survives regenerating, in two places: the
 * user's file, and the generated file's regions ({@see Regions}). Both
 * files start with `// dextrin:schema NAME`, by which a schema's files are
 * found again: its class is named and placed as the user's file has it,
 * and the generated parent follows that name (`Purchase` makes
 * `AbstractPurchase`).
 */
final class Php
{
    /** The first line of every generated file, after `<?php`. */
    public const GENERATED = '// Generated by bin/dextrin gen-php';

    private function __construct()
    {
    }

    /**
     * Generates the classes for the schemas under `$roots` into `$out`, in
     * the namespace `$namespace`: the generated files rewritten, the user's
     * files written once. A generated parent whose class the user renamed
     * moves with it; the old file is removed.
     *
     * @param list<string> $roots `.dxns` files or directories
     * @param string $namespace the namespace `$out` stands for (PSR-4)
     * @param string $out the directory written into
     * @return list<string> the paths written, sorted
     * @throws CodegenError when the schemas do not load, or a schema can't be generated; nothing is written then
     */
    public static function write(array $roots, string $namespace, string $out): array
    {
        ['files' => $files, 'stale' => $stale] = self::files($roots, $namespace, $out);
        $written = [];
        foreach ($files as [$path, $content, $kind]) {
            if ($kind === 'user' && file_exists($path)) {
                continue;
            }
            if (!is_dir(dirname($path))) {
                mkdir(dirname($path), 0777, true);
            }
            file_put_contents($path, $content);
            $written[] = $path;
        }
        foreach ($stale as $path) {
            unlink($path);
        }
        sort($written);
        return $written;
    }

    /**
     * Whether the generated files under `$out` are what {@see self::write()}
     * would write now, with no orphaned region in them: every problem,
     * each naming a file; `[]` when there is none. For CI.
     *
     * @param list<string> $roots `.dxns` files or directories
     * @param string $namespace the namespace `$out` stands for
     * @param string $out the directory generated into
     * @return list<string> the problems
     * @throws CodegenError when the schemas do not load, or a schema can't be generated
     */
    public static function check(array $roots, string $namespace, string $out): array
    {
        ['files' => $files, 'stale' => $stale] = self::files($roots, $namespace, $out);
        $problems = [];
        foreach ($files as [$path, $content, $kind]) {
            if ($kind !== 'generated') {
                continue;
            }
            $now = is_file($path) ? file_get_contents($path) : null;
            if ($now === null) {
                $problems[] = "{$path} is missing";
            } elseif ($now !== $content) {
                $problems[] = "{$path} is out of date with its schema";
            }
            foreach (Regions::orphans($content) as $name) {
                $problems[] = "{$path} holds the orphaned region {$name}: move its code or delete it";
            }
        }
        foreach ($stale as $path) {
            $problems[] = "{$path} belongs to a class that has been renamed: regenerate to remove it";
        }
        return $problems;
    }

    /**
     * Every file, `[path, content, 'generated'|'user']`, and the generated
     * files left from a class since renamed.
     *
     * @param list<string> $roots
     * @return array{files: list<array{0: string, 1: string, 2: string}>, stale: list<string>}
     * @throws CodegenError
     */
    private static function files(array $roots, string $namespace, string $out): array
    {
        $namespace = trim($namespace, '\\');
        $out = rtrim($out, '/');
        $loaded = Tree::load($roots);
        if (!$loaded['ok']) {
            throw new CodegenError(array_map(static fn (array $p): string => "{$p['file']}:{$p['line']}: {$p['message']}", $loaded['problems']));
        }
        $registry = $loaded['registry'];
        $schemas = $registry->structSchemas();
        ksort($schemas);

        $known = self::known($out);
        $classes = [];
        foreach (array_keys($schemas) as $name) {
            $classes[$name] = self::classFor($name, $namespace, $out, $known);
        }
        self::refuseClashes($classes, $namespace);

        $files = [[self::path($out, 'Decoder'), self::decoderFile($namespace, $classes), 'generated']];
        $stale = [];
        $problems = [];
        foreach ($schemas as $name => $versions) {
            ksort($versions);
            /** @var list<Compiled> $ordered */
            $ordered = array_values($versions);
            $class = $classes[$name];
            try {
                $generated = (new PhpClass($name, $ordered, $class, $classes, $registry))->source();
            } catch (Unsupported $e) {
                $problems[] = "{$name}({$e->version}): {$e->getMessage()}";
                continue;
            }
            $oldPath = $known[$name]['gen'] ?? $class['gen'];
            $old = is_file($oldPath) ? (string) file_get_contents($oldPath) : null;
            $files[] = [$class['gen'], Regions::merge($generated, $old), 'generated'];
            $files[] = [$class['user'], self::userFile($name, $class), 'user'];
            if ($oldPath !== $class['gen'] && is_file($oldPath)) {
                $stale[] = $oldPath;
            }
        }
        if ($problems !== []) {
            throw new CodegenError($problems);
        }
        return ['files' => $files, 'stale' => $stale];
    }

    // ---- names and paths, kept ------------------------------------------------------

    /**
     * The files under `$out` that say which schema they are: by schema, the
     * user's file with its namespace and class, and the generated file.
     *
     * @return array<string, array{user?: string, namespace?: string, class?: string, gen?: string}>
     * @throws CodegenError two files of one kind for one schema
     */
    private static function known(string $out): array
    {
        if (!is_dir($out)) {
            return [];
        }
        $paths = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($out, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file instanceof \SplFileInfo && $file->isFile() && str_ends_with($file->getFilename(), '.php')) {
                $paths[] = $file->getPathname();
            }
        }
        sort($paths);
        $known = [];
        $problems = [];
        foreach ($paths as $path) {
            $text = (string) file_get_contents($path);
            if (preg_match('/^\/\/ dextrin:schema (\S+)$/m', $text, $m) !== 1) {
                continue;
            }
            $schema = $m[1];
            $kind = str_contains($text, "\n" . self::GENERATED) ? 'gen' : 'user';
            if (isset($known[$schema][$kind])) {
                $problems[] = "{$known[$schema][$kind]} and {$path} are both the schema {$schema}";
                continue;
            }
            if ($kind === 'gen') {
                $known[$schema]['gen'] = $path;
                continue;
            }
            if (
                preg_match('/^namespace\s+([^;\s]+)\s*;/m', $text, $ns) !== 1
                || preg_match('/^(?:(?:final|abstract|readonly)\s+)*class\s+(\w+)/m', $text, $cls) !== 1
            ) {
                $problems[] = "{$path} is the schema {$schema}, but holds no namespaced class";
                continue;
            }
            $known[$schema] = ($known[$schema] ?? []) + ['user' => $path, 'namespace' => $ns[1], 'class' => $cls[1]];
        }
        if ($problems !== []) {
            throw new CodegenError($problems);
        }
        return $known;
    }

    /**
     * A schema's class and files: as the user's file has them when there
     * is one, otherwise derived -- `acme.shop/Order` under `NS` is
     * `NS\Acme\Shop\Order` in `Acme/Shop/Order.php`, each namespace part a
     * directory written as its namespace part is (PSR-4), whatever case the
     * DXNS namespace was written in.
     *
     * @param array<string, array{user?: string, namespace?: string, class?: string, gen?: string}> $known
     * @return array{namespace: string, class: string, fqcn: string, user: string, gen: string}
     */
    private static function classFor(string $name, string $namespace, string $out, array $known): array
    {
        $entry = $known[$name] ?? [];
        if (isset($entry['user'], $entry['namespace'], $entry['class'])) {
            $ns = $entry['namespace'];
            $class = $entry['class'];
            $user = $entry['user'];
        } else {
            [$parts, $local] = self::split($name);
            $parts = array_map(self::identifier(...), $parts);
            $class = self::identifier($local);
            $ns = implode('\\', array_filter([$namespace, ...$parts], static fn (string $p): bool => $p !== ''));
            $user = self::path($out, implode('/', [...$parts, $class]));
        }
        return [
            'namespace' => $ns,
            'class' => $class,
            'fqcn' => "{$ns}\\{$class}",
            'user' => $user,
            'gen' => dirname($user) . "/Abstract{$class}.php",
        ];
    }

    private static function path(string $out, string $relative): string
    {
        return "{$out}/{$relative}.php";
    }

    /**
     * A schema name's namespace parts and local name.
     *
     * @return array{0: list<string>, 1: string}
     */
    private static function split(string $name): array
    {
        $slash = strrpos($name, '/');
        if ($slash === false) {
            return [[], $name];
        }
        return [explode('.', substr($name, 0, $slash)), substr($name, $slash + 1)];
    }

    /** A DXNS name part as a PHP class or namespace name: `order-line` is `OrderLine`, `shop` is `Shop`. */
    private static function identifier(string $part): string
    {
        $words = preg_split('/[^A-Za-z0-9\x80-\xff]+/', $part, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $name = implode('', array_map(ucfirst(...), $words));
        if ($name === '') {
            return '_';
        }
        return ctype_digit($name[0]) ? "_{$name}" : $name;
    }

    /**
     * Two schemas given one class, or one named like another's generated
     * parent, or like the decoder, are refused, naming both.
     *
     * @param array<string, array{namespace: string, class: string, fqcn: string, user: string, gen: string}> $classes
     * @throws CodegenError
     */
    private static function refuseClashes(array $classes, string $namespace): void
    {
        $taken = [strtolower("{$namespace}\\Decoder") => 'the generated decoder'];
        $problems = [];
        foreach ($classes as $name => $class) {
            $parent = "{$class['namespace']}\\Abstract{$class['class']}";
            foreach ([[$class['fqcn'], "the schema {$name}"], [$parent, "the generated parent of the schema {$name}"]] as [$fqcn, $what]) {
                $key = strtolower($fqcn);
                if (isset($taken[$key])) {
                    $problems[] = "{$fqcn} would be both {$taken[$key]} and {$what}: rename one";
                } else {
                    $taken[$key] = $what;
                }
            }
        }
        if ($problems !== []) {
            throw new CodegenError($problems);
        }
    }

    // ---- the user's file and the decoder -----------------------------------------------

    /** @param array{namespace: string, class: string, fqcn: string, user: string, gen: string} $class */
    private static function userFile(string $name, array $class): string
    {
        return <<<PHP
            <?php

            // dextrin:schema {$name}

            declare(strict_types=1);

            namespace {$class['namespace']};

            /**
             * The schema {$name}. Its properties and methods come from
             * {@see Abstract{$class['class']}}, which `bin/dextrin gen-php` rewrites;
             * this file is yours and is never rewritten.
             */
            class {$class['class']} extends Abstract{$class['class']}
            {
            }

            PHP;
    }

    /**
     * `NS\Decoder`: DXN text decoded, every struct of a known schema read
     * with its class's generated `read()` -- no registry, so no schema at
     * run time.
     *
     * @param array<string, array{namespace: string, class: string, fqcn: string, user: string, gen: string}> $classes
     */
    private static function decoderFile(string $namespace, array $classes): string
    {
        $constant = '';
        $arms = '';
        foreach ($classes as $name => $class) {
            $quoted = var_export($name, true);
            $constant .= "        {$quoted} => \\{$class['fqcn']}::class,\n";
            $arms .= "                {$quoted} => \\{$class['fqcn']}::read(\$value),\n";
        }
        $generated = self::GENERATED;
        return <<<PHP
            <?php

            {$generated}.
            // Regenerating rewrites it: do not edit it.

            declare(strict_types=1);

            namespace {$namespace};

            use JOetjen\\Dextrin\\Codegen\\InvalidData;
            use JOetjen\\Dextrin\\Codegen\\Runtime;
            use JOetjen\\Dextrin\\Dextrin;
            use JOetjen\\Dextrin\\DXNError;
            use JOetjen\\Dextrin\\Registry;
            use JOetjen\\Dextrin\\Value\\DXNStruct;

            /**
             * DXN decoded into the generated classes: every struct of a schema
             * this namespace was generated from is read by its class's `read()`,
             * wherever it stands -- inside lists and maps too. Any other value is
             * left as it is decoded.
             */
            final class Decoder
            {
                /** The class generated for each schema, by schema name. */
                public const CLASSES = [
            {$constant}    ];

                private function __construct()
                {
                }

                /**
                 * The class generated for each schema, by schema name.
                 *
                 * @return array<string, class-string>
                 */
                public static function classes(): array
                {
                    return self::CLASSES;
                }

                /**
                 * `\$text` decoded, its structs read into the generated classes.
                 * `\$registry` and `\$strict` are as {@see Dextrin::decode()} takes
                 * them; `\$deprecations` (`once`, `every`, `off`, `error`) and
                 * `\$onDeprecated` say how what is deprecated warns
                 * ({@see Runtime::reading()}).
                 *
                 * @param string \$text the DXN text
                 * @param Registry|null \$registry as {@see Dextrin::decode()} takes it
                 * @param bool|null \$strict as {@see Dextrin::decode()} takes it
                 * @param string \$deprecations how often deprecated things warn
                 * @param callable|null \$onDeprecated receives each warning in place of `trigger_error()`
                 * @return mixed the value
                 * @throws DXNError when the text does not decode
                 * @throws InvalidData when a struct is refused
                 */
                public static function decode(
                    string \$text,
                    ?Registry \$registry = null,
                    ?bool \$strict = null,
                    string \$deprecations = 'once',
                    ?callable \$onDeprecated = null,
                ): mixed {
                    return self::read(Dextrin::decode(\$text, \$registry, \$strict), \$deprecations, \$onDeprecated);
                }

                /**
                 * A decoded value with its structs read into the generated classes;
                 * the options as {@see self::decode()} takes them.
                 *
                 * @param mixed \$value the decoded value
                 * @param string \$deprecations how often deprecated things warn
                 * @param callable|null \$onDeprecated receives each warning
                 * @return mixed the value, its structs read
                 * @throws InvalidData when a struct is refused
                 */
                public static function read(mixed \$value, string \$deprecations = 'once', ?callable \$onDeprecated = null): mixed
                {
                    return Runtime::reading(\$deprecations, \$onDeprecated, static fn (): mixed => self::walk(\$value));
                }

                /** One value read, and every value inside it. */
                private static function walk(mixed \$value): mixed
                {
                    if (!\$value instanceof DXNStruct) {
                        return Runtime::walk(\$value, self::walk(...));
                    }
                    return match (\$value->name) {
            {$arms}                default => \$value,
                    };
                }
            }

            PHP;
    }
}
